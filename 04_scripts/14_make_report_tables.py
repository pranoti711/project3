"""
14_make_report_tables.py - turn the result CSVs into ready-to-paste Markdown tables.

Reads  05_results/tables/*.csv  (and 05_results_origoutcome_run/tables for the comparison, if present)
Writes 00_docs/11_results_tables.md
Run   : python 04_scripts/14_make_report_tables.py          (after run_from_07.py has finished)
Every number in the write-up (00_docs/10_results_writeup.md) should match this file; if you re-run the
pipeline, re-run this script and update the write-up from it.
"""
import argparse
from pathlib import Path
import pandas as pd


def find_root():
    p = Path.cwd().resolve()
    for q in [p, *p.parents]:
        if (q / "04_scripts").is_dir():
            return q
        if (q / "project3" / "04_scripts").is_dir():
            return q / "project3"
    raise SystemExit("Run from inside project3.")


ap = argparse.ArgumentParser()
ap.add_argument("--results", default="05_results", help="results folder, e.g. 05_results_stage2")
ap.add_argument("--out", default="11_results_tables.md", help="file name written inside 00_docs")
ARGS = ap.parse_args()
ROOT = find_root()
T = ROOT / ARGS.results / "tables"
OUT = ROOT / "00_docs" / ARGS.out


def rd(name, base=T):
    f = base / name
    return pd.read_csv(f) if f.exists() else None


def fmt(v, nd=3, signed=False):
    if pd.isna(v):
        return ""
    if isinstance(v, (int,)) or (isinstance(v, float) and float(v).is_integer() and abs(v) > 5):
        return f"{int(v)}"
    return f"{v:+.{nd}f}" if signed else f"{v:.{nd}f}"


def md(df, signed=(), nd=3):
    if df is None or df.empty:
        return "_(table not found)_\n"
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, str) or isinstance(v, (bool,)):
                cells.append(str(v))
            else:
                cells.append(fmt(v, nd, signed=c in signed))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


parts = ["# 11_results_tables.md - auto-generated by 04_scripts/14_make_report_tables.py\n",
         "Do not edit by hand; re-run the script.\n"]

sc = rd("model_scores_lfo.csv")
parts += ["\n## 1. Leave-future-out scores (within year x disease AUC = `auc`)\n", md(sc)]

dl = rd("model_delta_auc_lfo.csv")
if dl is not None:
    dl = dl.copy(); dl["ci95"] = dl.apply(lambda r: f"[{r.lo:+.3f}, {r.hi:+.3f}]", axis=1)
    parts += ["\n## 2. Delta AUC vs model A (95% county-cluster bootstrap)\n",
              md(dl[["scope", "model", "delta_auc", "ci95"]], signed=("delta_auc",))]

cal = rd("calibration_by_year.csv")
parts += ["\n## 3. Observed vs predicted event rate by test year (model A)\n", md(cal, nd=4)]

pl = rd("placebo_group_tests_holm.csv")
if pl is not None:
    parts += ["\n## 4. Placebo tests per group, Holm-corrected\n",
              md(pl[["group", "events", "observed_delta_auc", "n1_p", "n1_p_holm", "n2_p", "n2_p_holm", "supported"]],
                 signed=("observed_delta_auc",))]

vs = rd("validation_summary.csv")
parts += ["\n## 5. Held-out transfer (AUC gain over A)\n", md(vs, signed=("mean_delta_auc", "median_delta_auc"), nd=4)]

sp = rd("spatial_block_cv.csv")
if sp is not None:
    w = sp.pivot(index="block", columns="model", values="auc").reset_index()
    w["block"] = w["block"].astype(int).astype(str)
    for m in [c for c in w.columns if c in ("B", "C", "D")]:
        w[f"d{m}"] = w[m] - w["A"]
    parts += ["\n## 6. Spatial-block CV (AUC per held-out block)\n", md(w, signed=("dB", "dC", "dD"))]
    d = {m: w[f"d{m}"] for m in ("B", "C", "D") if f"d{m}" in w}
    parts.append("\n" + "; ".join(f"model {m}: better than A in {(v > 0).sum()} of {len(v)} blocks, mean {v.mean():+.4f}"
                                   for m, v in d.items()) + "\n")

mo = rd("residual_moran.csv")
if mo is not None:
    parts += ["\n## 7. Moran's I of out-of-sample residuals (pooled)\n",
              md(mo[mo["scope"] == "residual_pooled"][["model", "I", "p"]], nd=4)]

ew = rd("early_warning_matched_far.csv")
if ew is not None:
    ew = ew[ew["scope"] == "all"] if "scope" in ew else ew
    parts += ["\n## 8. Early warning at matched false-alarm rate\n",
              md(ew[["model", "far", "hit_rate", "gain_vs_A", "gain_lo", "gain_hi"]], signed=("gain_vs_A", "gain_lo", "gain_hi"))]

lt = rd("leadtime_summary.csv")
if lt is not None:
    parts.append(f"\n## 9. Lead-time tests\n\nTests: {len(lt)}. Holm p < 0.05: {(lt['perm_p_holm'] < 0.05).sum()}. "
                 f"Smallest unadjusted p: {lt['perm_p_one_sided'].min():.3f}. Smallest Holm p: {lt['perm_p_holm'].min():.3f}.\n")

cc = rd("confound_check.csv")
if cc is not None:
    parts += ["\n## 10. Confound check (stand-in logistic model; direction, not exact AUC)\n", md(cc, signed=("delta_vs_A", "delta_vs_A_nopop"))]

orig = ROOT / "05_results_origoutcome_run" / "tables"
if (orig / "model_delta_auc_lfo.csv").exists():
    o = pd.read_csv(orig / "model_delta_auc_lfo.csv"); o["ci95"] = o.apply(lambda r: f"[{r.lo:+.3f}, {r.hi:+.3f}]", axis=1)
    parts += ["\n## 11. First pass for comparison (original outcome, mortality levels, no population in A) - NOT the headline\n",
              md(o[["scope", "model", "delta_auc", "ci95"]], signed=("delta_auc",))]

OUT.write_text("\n".join(parts), encoding="utf-8")
print("Wrote", OUT)
