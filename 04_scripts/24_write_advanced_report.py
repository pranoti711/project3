"""
24_write_advanced_report.py - turns the advanced-layer tables into a readable report with computed sentences.

Reads  05_results/tables/adv_*.csv (made by scripts 20, 21, 22)
Writes 00_docs/20_advanced_results.md
Every number comes from the tables; nothing is typed by hand, so the report always matches the latest run.
Run    python 04_scripts/24_write_advanced_report.py
"""
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from adv_common import find_root  # noqa: E402

root = find_root()
tab = root / "05_results" / "tables"


def rd(n):
    f = tab / n
    return pd.read_csv(f) if f.exists() else None


def md(df, nd=3):
    if df is None:
        return "_(table not found; run the script that makes it)_\n"
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            cells.append(str(v) if isinstance(v, (str, bool)) else (f"{v:.{nd}f}" if pd.notna(v) else ""))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


eq, meta, mde = rd("adv_equivalence.csv"), rd("adv_meta_analysis.csv"), rd("adv_mde.csv")
gd, gi, dd = rd("adv_gbm_delta.csv"), rd("adv_gbm_importance.csv"), rd("adv_decision_diff.csv")
out = ["# 20_advanced_results.md - advanced evaluation layer (auto-generated by 04_scripts/24_write_advanced_report.py)\n",
       "Not new hypothesis tests. These analyses quantify how small an effect the study can rule out and check that the null "
       "is not an artefact of the model type. They use the same test rows and events as the main analysis.\n"]

out.append("\n## 1. How small an effect can be ruled out (equivalence)\n")
if eq is not None:
    b = eq[eq["contrast"] == "B-A"].iloc[0]
    out.append(f"For the mortality contrast B - A the 90% bootstrap interval is [{b.ci90_lo:+.3f}, {b.ci90_hi:+.3f}] AUC. "
               f"It lies inside +/-0.03: **{'yes' if b['equiv_within_0.03'] else 'no'}**; inside +/-0.02: "
               f"**{'yes' if b['equiv_within_0.02'] else 'no'}**; inside +/-0.05: **{'yes' if b['equiv_within_0.05'] else 'no'}**. "
               "An interval inside a margin means any true effect larger than the margin is rejected.\n\n")
    out.append(md(eq))
out.append("\n## 2. Minimum detectable effect\n")
if mde is not None:
    m = mde.iloc[0]
    out.append(f"With a bootstrap standard error of {m.observed_se:.4f} for B - A, the study had 80% power to detect a true gain of "
               f"about **{m.mde_80pct_power:.3f} AUC** and 90% power for {m.mde_90pct_power:.3f}. Smaller gains could exist and would "
               "not have been detected.\n\n" + md(mde, 4))
out.append("\n## 3. Heterogeneity across diseases (random-effects meta-analysis of B - A)\n")
if meta is not None:
    r = meta.iloc[0]
    out.append(f"Over {int(r.k)} diseases the pooled change in AUC is {r.pooled:+.3f} (95% CI {r.lo:+.3f} to {r.hi:+.3f}); "
               f"between-disease variance tau^2 = {r.tau2:.4f}, I^2 = {r.I2:.0f}%; 95% prediction interval {r.pred_lo:+.3f} to "
               f"{r.pred_hi:+.3f}. A low I^2 means no evidence that mortality helps some diseases and not others beyond chance.\n")
out.append("\n## 4. Does a non-linear learner find a signal? (gradient boosting)\n")
if gd is not None:
    for _, r in gd.iterrows():
        out.append(f"- {r.contrast}: {r.delta:+.3f} (95% CI {r.ci95_lo:+.3f} to {r.ci95_hi:+.3f})\n")
    out.append("\n" + md(gd))
if gi is not None:
    out.append("\nPermutation importance of the mortality features in the boosted model (drop in AUC when a column is shuffled). "
               "A feature can be used by the model without improving out-of-sample AUC overall; that pattern signals fitting noise.\n\n"
               + md(gi, 4))
out.append("\n## 5. Practical value (decision curve)\n")
if dd is not None:
    out.append("Net-benefit difference versus model A at selected alarm thresholds, with 95% county-cluster intervals. An interval "
               "that includes 0 means no demonstrated practical gain.\n\n" + md(dd, 5))
open(root / "00_docs" / "20_advanced_results.md", "w", encoding="utf-8").write("".join(out))
print("Wrote 00_docs/20_advanced_results.md")
