"""
record_environment.py - writes 00_docs/19_environment.md with the Python, package and R/INLA versions used.
Run from project3:  python tools/record_environment.py
"""
import platform
import subprocess
import sys
from datetime import date
from importlib import metadata
from pathlib import Path

root = Path.cwd()
pk = ["pandas", "numpy", "scipy", "scikit-learn", "matplotlib", "pyshp", "pyyaml"]
lines = ["# 19_environment.md - software versions (auto-generated by tools/record_environment.py)", "",
         f"Date: {date.today()}", f"Python: {sys.version.split()[0]} on {platform.platform()}", "", "## Python packages"]
for p in pk:
    try:
        lines.append(f"- {p}: {metadata.version(p)}")
    except metadata.PackageNotFoundError:
        lines.append(f"- {p}: not installed")
lines += ["", "## R and R-INLA"]
try:
    out = subprocess.run(["Rscript", "-e", "cat(R.version.string, '\\n'); for (p in c('INLA','data.table','sf','spdep')) cat(p, ':', tryCatch(as.character(packageVersion(p)), error=function(e) 'not installed'), '\\n')"],
                         capture_output=True, text=True, timeout=120)
    lines.append("```\n" + (out.stdout or out.stderr).strip() + "\n```")
except Exception as e:  # Rscript missing
    lines.append(f"Rscript not available here ({e}). Run this in a terminal that has R, or copy `sessionInfo()` by hand.")
lines += ["", "Random seeds are listed in `03_config/seeds.yaml`."]
(root / "00_docs" / "19_environment.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("Wrote 00_docs/19_environment.md")
